/*
  ABU SHUJAA PHARMACY — INVENTORY SYNC SCRIPT
  ---------------------------------------------
  Pulls the full inventory from the Google Sheet (via the Apps Script
  Web App's "export" action) and regenerates products.js in the repo
  root. Run by the GitHub Action in .github/workflows/sync-inventory.yml,
  or manually with: node inventory-scanner/sync-inventory.js

  Requires two environment variables:
    APPS_SCRIPT_URL  — your deployed Web App URL (same as in scan.html)
    APPS_SCRIPT_KEY  — your SECRET_KEY (same as in Code.gs)
*/

const fs = require("fs");
const path = require("path");

const SCRIPT_URL = process.env.APPS_SCRIPT_URL;
const SECRET_KEY = process.env.APPS_SCRIPT_KEY;

if (!SCRIPT_URL || !SECRET_KEY) {
  console.error("Missing APPS_SCRIPT_URL or APPS_SCRIPT_KEY environment variables.");
  process.exit(1);
}

function esc(s) {
  return String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"');
}

async function main() {
  const url = `${SCRIPT_URL}?action=export&key=${encodeURIComponent(SECRET_KEY)}`;
  const res = await fetch(url);
  const data = await res.json();

  if (!data.ok) {
    console.error("Export failed:", data.error || "unknown error");
    process.exit(1);
  }

  const products = data.products;
  console.log(`Fetched ${products.length} products from the sheet.`);

  const lines = [];
  lines.push(`/*
  ABU SHUJAA PHARMACY — INVENTORY DATA
  -------------------------------------
  AUTO-GENERATED by inventory-scanner/sync-inventory.js — do not edit
  this file by hand, your changes will be overwritten on the next sync.

  To change a product: edit it in the Google Sheet (or via the phone
  scanner at scan.html), then re-run the sync (it also runs on a
  schedule via GitHub Actions).

  Fields:
    id        – position in the sheet at time of sync (stable enough
                for display purposes; not a permanent product ID)
    name, category, price, discount, info, rx, qty — as in the sheet
    image     – optional path, e.g. "assets/products/1.jpg"
*/

const PRODUCTS = [`);

  products.forEach((p, i) => {
    const id = i + 1;
    const imagePart = p.image ? `, image: "${esc(p.image)}"` : "";
    lines.push(
      `  { id: ${id}, name: "${esc(p.name)}", category: "${esc(p.category || "General")}", price: ${Number(p.price) || 0}, discount: ${Number(p.discount) || 0}, info: "${esc(p.info || "")}", rx: ${p.rx ? "true" : "false"}, qty: ${Number(p.qty) || 0}${imagePart} },`
    );
  });

  lines.push("];\n");

  const outPath = path.join(__dirname, "..", "products.js");
  const content = lines.join("\n");
  const existing = fs.existsSync(outPath) ? fs.readFileSync(outPath, "utf8") : "";

  if (content === existing) {
    console.log("No changes — products.js already up to date.");
    return;
  }

  fs.writeFileSync(outPath, content, "utf8");
  console.log(`Wrote ${outPath} (${products.length} products).`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
